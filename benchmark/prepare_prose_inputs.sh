#!/usr/bin/env bash
# prepare_prose_inputs.sh - generate the temporary ProSE entrapment inputs.
#
# Creates (deterministically; nothing is vendored or committed):
#   <out>/entrapment_target.fasta  P02769 target + ENTRAPMENT_-prefixed real
#                                  E. coli K-12 target proteins, via
#                                  make_entrapment_fasta.py (decoys are NOT
#                                  copied - ProSE generates its own via
#                                  -Search:decoys auto)
#   <out>/bsa_merged.mzML          BSA1+BSA2+BSA3.mzML merged with FileMerger
#   <out>/PROVENANCE.txt           source paths + sha256 of inputs/outputs
#
# Usage: prepare_prose_inputs.sh <openms-checkout> <build-bin-dir> [out-dir]
#   <openms-checkout>  source tree at the pinned commit; expected inputs:
#                      doc/pyopenms/src/data/P02769.fasta,
#                      share/OpenMS/examples/BSA/BSA{1,2,3}.mzML,
#                      share/OpenMS/examples/TOPPAS/data/Identification/
#                      target_decoy_Ecoli_K12_TaxID_83333.proteomes.fasta
#   <build-bin-dir>    build/bin containing FileMerger
#   [out-dir]          default: benchmark/generated/prose (git-ignored)
#
# Re-running reproduces the same bytes: the FASTA generator is
# order-deterministic and FileMerger concatenates in argument order.
set -euo pipefail

OPENMS_ROOT="${1:?usage: prepare_prose_inputs.sh <openms-checkout> <build-bin-dir> [out-dir]}"
BUILD_BIN="${2:?missing build-bin-dir argument}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_DIR="${3:-${HERE}/generated/prose}"

P02769="${OPENMS_ROOT}/doc/pyopenms/src/data/P02769.fasta"
ECOLI="${OPENMS_ROOT}/share/OpenMS/examples/TOPPAS/data/Identification/target_decoy_Ecoli_K12_TaxID_83333.proteomes.fasta"
FILEMERGER="${BUILD_BIN}/FileMerger"

missing=()
for f in "${P02769}" "${ECOLI}" "${FILEMERGER}" \
         "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA1.mzML" \
         "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA2.mzML" \
         "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA3.mzML"; do
  [[ -e "${f}" ]] || missing+=("${f}")
done
if [[ ${#missing[@]} -gt 0 ]]; then
  echo "ERROR: missing expected inputs:" >&2
  printf '  %s\n' "${missing[@]}" >&2
  exit 2
fi

mkdir -p "${OUT_DIR}"
rm -f "${OUT_DIR}/bsa_merged.mzML"

# (--force is safe here: OUT_DIR is owned by this script and fully regenerated)
python3 "${HERE}/make_entrapment_fasta.py" \
  --target "${P02769}" --ecoli "${ECOLI}" \
  --out "${OUT_DIR}/entrapment_target.fasta" --force

TMP_MZML="${OUT_DIR}/.bsa_merged.tmp.mzML"
rm -f "${TMP_MZML}"
"${FILEMERGER}" \
  -in "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA1.mzML" \
      "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA2.mzML" \
      "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA3.mzML" \
  -out "${TMP_MZML}"
mv "${TMP_MZML}" "${OUT_DIR}/bsa_merged.mzML"

{
  echo "# generated by benchmark/prepare_prose_inputs.sh (temporary, not vendored)"
  echo "openms_root=${OPENMS_ROOT}"
  for f in "${P02769}" "${ECOLI}" \
           "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA1.mzML" \
           "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA2.mzML" \
           "${OPENMS_ROOT}/share/OpenMS/examples/BSA/BSA3.mzML"; do
    sha256sum "${f}"
  done
  sha256sum "${OUT_DIR}/entrapment_target.fasta" "${OUT_DIR}/bsa_merged.mzML"
} > "${OUT_DIR}/PROVENANCE.txt"

echo "generated inputs in ${OUT_DIR}:"
ls -la "${OUT_DIR}"
